interface I18nValue {
  lang: Lang;
  setLang: (lang: Lang) => void;
  t: (key: string, vars?: Record<string, string | number>) => string;
}

const I18nContext = createContext<I18nValue | null>(null);

function readStoredLang(): Lang | null {
  if (typeof window === 'undefined') return null;
  const value = window.localStorage.getItem(STORAGE_KEY);
  return value === 'en' || value === 'am' ? value : null;
}

function telegramLang(): Lang | null {
  const code = getTelegramWebApp()?.initDataUnsafe?.user?.language_code;
  return code?.toLowerCase().startsWith('am') ? 'am' : null;
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const { user } = useSession();
  const [lang, setLangState] = useState<Lang>('en');
  const adoptedUser = useRef<string | null>(null);

  useEffect(() => {
    const stored = readStoredLang();
    setLangState(stored ?? telegramLang() ?? 'en');
  }, []);

  useEffect(() => {
    if (!user || adoptedUser.current === user.id) return;
    adoptedUser.current = user.id;
    if (user.locale === 'en' || user.locale === 'am') {
      setLangState(user.locale);
      window.localStorage.setItem(STORAGE_KEY, user.locale);
    }
  }, [user]);

  const setLang = useCallback(
    (next: Lang) => {
      setLangState(next);
      if (typeof window !== 'undefined') window.localStorage.setItem(STORAGE_KEY, next);
      if (user) void updateLocale(next).catch(() => undefined);
    },
    [user],
  );

  const t = useCallback(
    (key: string, vars?: Record<string, string | number>) => {
      let text = DICT[lang][key] ?? DICT.en[key] ?? key;
      if (vars) {
        for (const [name, value] of Object.entries(vars)) {
          text = text.replaceAll(`{${name}}`, String(value));
        }
      }
      return text;
    },
    [lang],
  );

  const value = useMemo<I18nValue>(() => ({ lang, setLang, t }), [lang, setLang, t]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nValue {
  const value = useContext(I18nContext);
  if (!value) throw new Error('useI18n must be used inside I18nProvider');
  return value;
}
